def build_supervisor_prompt() -> str:
    """组装 Supervisor 系统提示词（自动注入可转移目标列表，随 worker 增删自动更新）。"""
    from app.agent.workers import WORKER_NAMES

    targets = "、".join(
        f"transfer_to_{k}（{WORKER_NAMES[k]}）" for k in WORKER_NAMES
    )
    return SUPERVISOR_SYSTEM_PROMPT.format(targets=targets)


